// Generates a differential corpus for the split engine (spec §14: "Dart and
// SQL results match exactly").
//
// The Dart engine is the reference: each case is computed here and written out
// with its answer, and supabase/tests/split_test.sql then requires the
// PL/pgSQL engine to reproduce it. Any divergence in the remainder rule, the
// tie-break order, or the order extras are applied turns that suite red.
//
// The seed is fixed, so the corpus is reproducible and reviewable in a diff:
//
//   dart run tool/gen_fuzz_vectors.dart

import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:hati/core/money/money.dart';
import 'package:hati/core/split/split.dart';

const int _seed = 20260925;
const int _caseCount = 240;

void main() {
  final random = Random(_seed);
  final cases = <Map<String, dynamic>>[];

  var attempts = 0;
  while (cases.length < _caseCount && attempts < _caseCount * 20) {
    attempts++;
    final mode = SplitMode.values[random.nextInt(SplitMode.values.length)];
    final input = _buildInput(random, mode);
    if (input == null) continue;

    try {
      final result = SplitEngine.compute(SplitRequest.fromJson(input));
      cases.add({
        'name': 'fuzz/${mode.name}/${cases.length}',
        'input': input,
        'expect': result.toJson(),
      });
    } on SplitException {
      // Randomly generated input that the engine rejects is not interesting
      // here — the hand-written vectors cover rejection deliberately.
      continue;
    }
  }

  final payload = {
    'note': 'GENERATED by tool/gen_fuzz_vectors.dart (seed $_seed). Do not '
        'edit by hand. The Dart engine produced every `expect`; the SQL '
        'engine must reproduce it exactly (spec §14).',
    'seed': _seed,
    'cases': cases,
  };

  File('supabase/tests/split_vectors_fuzz.json')
      .writeAsStringSync('${const JsonEncoder.withIndent('  ').convert(payload)}\n');

  stdout.writeln('wrote ${cases.length} vectors from $attempts attempts');
}

List<String> _ids(int n) => [for (var i = 0; i < n; i++) 'u$i'];

int _total(Random random) => 1 + random.nextInt(kMaxBillCentavos);

Map<String, dynamic>? _buildInput(Random random, SplitMode mode) {
  final n = 1 + random.nextInt(8);
  final ids = _ids(n);

  switch (mode) {
    case SplitMode.equal:
      return {
        'total': _total(random),
        'mode': 'equal',
        'participants': [for (final id in ids) {'user_id': id}],
      };

    case SplitMode.exact:
      final total = _total(random);
      final cuts = _partition(random, total, n);
      return {
        'total': total,
        'mode': 'exact',
        'participants': [
          for (var i = 0; i < n; i++) {'user_id': ids[i], 'input': cuts[i]},
        ],
      };

    case SplitMode.percent:
      // Hundredths of a percent, summing to exactly 10000.
      final cuts = _partition(random, 10000, n);
      if (cuts.any((c) => c < 0)) return null;
      return {
        'total': _total(random),
        'mode': 'percent',
        'participants': [
          for (var i = 0; i < n; i++) {'user_id': ids[i], 'input': cuts[i]},
        ],
      };

    case SplitMode.shares:
      return {
        'total': _total(random),
        'mode': 'shares',
        'participants': [
          for (final id in ids)
            {'user_id': id, 'input': 1 + random.nextInt(5000)},
        ],
      };

    case SplitMode.itemized:
      final itemCount = 1 + random.nextInt(6);
      final items = <Map<String, dynamic>>[];
      var subtotal = 0;

      for (var i = 0; i < itemCount; i++) {
        final assignees = <String>[
          for (final id in ids)
            if (random.nextBool()) id,
        ];
        if (assignees.isEmpty) assignees.add(ids[random.nextInt(n)]);

        final amount = random.nextInt(500000);
        subtotal += amount;
        items.add({
          'name': 'item$i',
          'amount': amount,
          'assignees': assignees,
        });
      }

      final serviceCharge = random.nextInt(subtotal ~/ 5 + 1);
      final tax = random.nextInt(subtotal ~/ 10 + 1);
      final discount = random.nextInt(subtotal ~/ 4 + 1);
      final total = subtotal + serviceCharge + tax - discount;
      if (total <= 0 || total > kMaxBillCentavos) return null;

      return {
        'total': total,
        'mode': 'itemized',
        'participants': [for (final id in ids) {'user_id': id}],
        'items': items,
        'extras': {
          'service_charge': serviceCharge,
          'tax': tax,
          'discount': discount,
        },
      };
  }
}

/// Splits [total] into [n] non-negative integers that sum to it exactly.
List<int> _partition(Random random, int total, int n) {
  if (n == 1) return [total];
  final cuts = <int>[
    for (var i = 0; i < n - 1; i++) random.nextInt(total + 1),
  ]..sort();

  final parts = <int>[];
  var previous = 0;
  for (final cut in cuts) {
    parts.add(cut - previous);
    previous = cut;
  }
  parts.add(total - previous);
  return parts;
}
